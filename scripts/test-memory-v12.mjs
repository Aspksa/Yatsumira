import assert from "node:assert/strict";
import {mkdtempSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {addKnowledge,coreStatus,withCoreDatabase} from "../server/core-db.mjs";
import {createMemoryTask,updateMemoryTask} from "../server/memory-v5-records.mjs";
import {assertGraphRelation} from "../server/universal-memory-graph.mjs";
import {proposeLesson,reviewLesson,lessons,learnFromOutcomes,feedbackMemory,feedbackPriority,researchGaps,learningReport} from "../server/memory-v12-learning.mjs";
import {graphLearningOverview,relationConfidence,analogyCandidates,ontologyCandidates,traceGraphAnomalies} from "../server/memory-v12-graph-learning.mjs";
import {retrievalPlan,adaptiveRecall,retrievalProfileProposal,profileExperiment,approveRetrievalProfile,recallQuality} from "../server/memory-v12-retrieval.mjs";
const cwd=process.cwd(),root=mkdtempSync(join(tmpdir(),"yatsumira-v12-"));
try{
  process.chdir(root);
  assert.equal(coreStatus().version,12);
  const first=addKnowledge({content:"«Проект Луна» использует «Модуль Заря» для проверки системы.",sector:0,source:"note"});
  const second=addKnowledge({content:"«Модуль Заря» находится в «Центр Знаний».",sector:1,source:"note"});
  const third=addKnowledge({content:"«Проект Солнце» использует «Модуль Заря».",sector:2,source:"note"});
  const id=source=>withCoreDatabase(db=>db.prepare("SELECT id FROM memory_entries WHERE source_kind='knowledge' AND source_id=?").get(source).id);
  const a=id(first.id),b=id(second.id),c=id(third.id);
  const claim=assertGraphRelation({memoryId:a,subject:"Проект Луна",subjectType:"project",predicate:"uses",object:"Модуль Заря",objectType:"module"});
  assertGraphRelation({memoryId:b,subject:"Модуль Заря",subjectType:"module",predicate:"located_in",object:"Центр Знаний",objectType:"organization"});
  assertGraphRelation({memoryId:c,subject:"Проект Солнце",subjectType:"project",predicate:"uses",object:"Модуль Заря",objectType:"module"});
  const lesson=proposeLesson({kind:"hypothesis",description:"Возможно проекты совместно используют модуль",memoryIds:[a,b]});
  assert.equal(lesson.state,"candidate");
  assert.equal(proposeLesson({kind:"hypothesis",description:"Возможно проекты совместно используют модуль",memoryIds:[b,a]}).stored,false);
  assert.equal(lessons().length,0);
  assert.equal(reviewLesson(lesson.id,{approved:true,evidence:"Два связанных исходных документа"}).state,"reviewed");
  assert.equal(lessons().length,1);
  assert.throws(()=>proposeLesson({kind:"success",description:"Утверждение",memoryIds:["not-a-memory"]}),/Active sources/);
  const feedback=feedbackMemory({query:"Проект Луна",memoryId:a,kind:"useful",evidence:"Результат поиска проверен вручную"});
  assert.equal(feedback.recorded,true);
  assert.ok(feedbackPriority(a).boost>0);
  assert.equal(researchGaps({query:"неизвестная космическая система"}).reviewState,"candidate");
  const t1=createMemoryTask({memoryId:a,title:"Проверить качество",checkpoint:"Проверка 1"});
  const t2=createMemoryTask({memoryId:b,title:"Проверить качество",checkpoint:"Проверка 2"});
  updateMemoryTask(t1.id,{status:"done",outcome:"Проверено"});
  updateMemoryTask(t2.id,{status:"done",outcome:"Повторено"});
  assert.equal(learnFromOutcomes().created,1);
  assert.equal(learnFromOutcomes().created,0);
  assert.equal(learningReport({persist:true}).pendingLessons,1);
  assert.ok(graphLearningOverview().linkCandidates.length>0);
  assert.ok(relationConfidence(a).some(x=>x.id===claim.id));
  assert.ok(Array.isArray(analogyCandidates()));
  assert.ok(Array.isArray(ontologyCandidates().types));
  assert.equal(traceGraphAnomalies().noDestructiveRepair,true);
  const plan=retrievalPlan("Как связан Проект Луна с Центром Знаний?");
  assert.ok(plan.limits.results>0);
  const result=adaptiveRecall("Проект Луна",{limit:6});
  assert.ok(result.results.some(x=>x.id===a));
  assert.equal(result.noModelRequired,true);
  assert.ok(recallQuality("Проект Луна",result.results).coverage>0);
  const profile=retrievalProfileProposal({name:"offline-balanced",weights:{lexical:.6,graph:.3,source:.1}});
  assert.equal(profile.state,"candidate");
  const cases=[{query:"Проект Луна",expectedId:a},{query:"Модуль Заря",expectedId:b}];
  const good=q=>q==="Проект Луна"?[{id:a}]:[{id:b}];
  const bad=q=>q==="Проект Луна"?[{id:c}]:[{id:a}];
  const failed=profileExperiment(cases,{baseline:good,candidate:bad});
  assert.equal(failed.accepted,false);
  assert.throws(()=>approveRetrievalProfile(profile.name,{evaluation:failed,evidence:"тест"}),/Passing/);
  const passed=profileExperiment(cases,{baseline:bad,candidate:good});
  assert.equal(passed.accepted,true);
  assert.equal(approveRetrievalProfile(profile.name,{evaluation:passed,evidence:"Проверено на 2 контрольных вопросах"}).automaticallyApplied,false);
  assert.deepEqual(withCoreDatabase(db=>db.prepare("PRAGMA foreign_key_check").all()),[]);
  assert.equal(withCoreDatabase(db=>db.prepare("PRAGMA integrity_check").get().integrity_check),"ok");
  console.log("[YATSUMIRA CORE v12] evidence learning, feedback, graph, retrieval and quality gates: OK");
}finally{process.chdir(cwd);rmSync(root,{recursive:true,force:true});}
