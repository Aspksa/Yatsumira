import assert from "node:assert/strict";
import {agenticMemorySearch,sourceAwareOrder,debateEvidence} from "../server/memory-v8-retrieval.mjs";
import {mkdtempSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {addKnowledge,coreStatus,withCoreDatabase} from "../server/core-db.mjs";
import {indexUniversalGraph,assertGraphRelation} from "../server/universal-memory-graph.mjs";
import {recordDecision,createMemoryTask,updateMemoryTask} from "../server/memory-v5-records.mjs";
import {fusionPreview,storeFusion,fusionSources,sourceInterference,experiencePatterns,memoryGaps,decisionOutcome,decisionHistory,memoryPriority} from "../server/memory-v8-learning.mjs";
import {graphMotifs,hypergraphPatterns,timeGraphEvolution,proposedGraphLinks,graphEmbeddingCandidates,graphConflictsAndImpact,evidenceGraphPath,recordGraphSnapshot} from "../server/memory-v8-graph.mjs";
import {scheduleMemoryJob,recoverInterruptedJobs,runMemoryJob,memoryJobStatus,memoryQualityWatch,compareMemoryAlgorithms,offlineMemoryStatus} from "../server/memory-v8-operations.mjs";
import {addHyperedge} from "../server/memory-v5-records.mjs";
const base=process.cwd(),dir=mkdtempSync(join(tmpdir(),"yatsumira-v8-"));
try{
  process.chdir(dir);
  assert.equal(coreStatus().version,8);
  const k1=addKnowledge({content:"«Сервис Альфа» использует «Система Лира». Сервис надёжен.",source:"note",sector:1});
  const k2=addKnowledge({content:"«Система Лира» находится в «Центр Омега». Исследования идут.",source:"note",sector:2});
  const k3=addKnowledge({content:"«Робот Сокол» использует «Сервис Альфа». Эксперимент проводится.",source:"note",sector:3});
  const mid=id=>withCoreDatabase(db=>db.prepare("SELECT id FROM memory_entries WHERE source_kind='knowledge' AND source_id=?").get(id).id);
  const ma=mid(k1.id),mb=mid(k2.id),mc=mid(k3.id);
  assert.equal(indexUniversalGraph({batch:25}).claims,3);
  const preview=fusionPreview("Сервис Альфа");
  assert.ok(Array.isArray(preview));

  assert.throws(()=>storeFusion([ma,mb],{kind:"semantic"}),/kind/);
  const fusion=storeFusion([ma,mb],{kind:"fusion"});
  assert.equal(fusion.stored,true);
  assert.equal(storeFusion([mb,ma],{kind:"fusion"}).stored,false);
  assert.equal(fusionSources(fusion.id).length,2);
  assert.ok(Array.isArray(sourceInterference("Сервис Альфа")));
  assert.ok(memoryGaps("неизвестный сверхпроект").missingTerms.length>=1);
  assert.ok(memoryPriority(ma).score>0);
  const decision=recordDecision({memoryId:ma,subject:"Платформа",choice:"Сервис Альфа"});
  const outcome=decisionOutcome({decisionId:decision.id,memoryId:mb,outcome:"Стабильность подтверждается испытаниями"});
  assert.equal(outcome.reviewed,false);
  assert.equal(decisionHistory(decision.id).length,1);
  const t1=createMemoryTask({memoryId:ma,title:"Проверка системы",checkpoint:"Шаг 1"});
  const t2=createMemoryTask({memoryId:mb,title:"Проверка системы",checkpoint:"Шаг 2"});
  updateMemoryTask(t1.id,{status:"done",outcome:"Успешно"});
  updateMemoryTask(t2.id,{status:"cancelled",outcome:"Не выполнено"});
  const patterns=experiencePatterns({limit:10});
  assert.equal(patterns[0].attempts,2);
  assert.equal(patterns[0].completed,1);
  assert.ok(Array.isArray(graphMotifs()));
  assert.ok(Array.isArray(proposedGraphLinks()));
  assert.ok(graphEmbeddingCandidates({limit:10}).every(x=>x.representation==="structural-not-neural-embedding"));
  assert.ok(Array.isArray(graphConflictsAndImpact().candidates));
  assert.equal(evidenceGraphPath("Робот Сокол","Центр Омега")[0].sourceMemoryIds.length,3);
  const initial=recordGraphSnapshot({asOf:"2026-11-16"});
  assert.equal(initial.stored,true);
  assert.equal(recordGraphSnapshot({asOf:"2026-11-16"}).stored,false);
  const future=timeGraphEvolution("2025-01-01","2027-01-01");
  assert.ok(future.added.length>=3);
  const nodes=withCoreDatabase(db=>db.prepare("SELECT id,label FROM graph_nodes").all());
  addHyperedge({memoryId:ma,relationType:"collaboration",participants:[
    {nodeId:nodes[0].id,role:"source"},{nodeId:nodes[1].id,role:"target"}]});
  assert.ok(hypergraphPatterns().hyperedges.length>=1);
  const search=await agenticMemorySearch("Сервис Альфа",{limit:6,maxRounds:2});
  assert.ok(search.results.some(x=>x.id===ma));
  assert.ok(search.rounds.length>=1);
  assert.equal(typeof search.insufficient,"boolean");
  assert.equal(sourceAwareOrder("Сервис Альфа",search.results,{limit:2}).length,2);
  assert.equal(debateEvidence("Сервис Альфа").notAutonomousVerdict,true);
  const scheduled=scheduleMemoryJob("health");
  assert.equal(scheduled.stored,true);
  assert.equal(scheduleMemoryJob("health").stored,false);
  assert.equal(runMemoryJob().state,"completed");
  const failJob=scheduleMemoryJob("knowledge-gaps",{query:"Робот Сокол"});
  assert.equal(failJob.stored,true);
  assert.equal(runMemoryJob().state,"completed");
  withCoreDatabase(db=>db.prepare("UPDATE memory_v8_tasks SET state='running' WHERE id=?").run(failJob.id));
  assert.equal(recoverInterruptedJobs().recovered,1);
  assert.equal(runMemoryJob().state,"completed");
  assert.ok(memoryJobStatus().some(x=>x.state==="completed"));
  assert.equal(memoryQualityWatch().ok,true);
  assert.equal(offlineMemoryStatus().localAvailable,true);
  const cases=[{query:"Сервис Альфа",expectedId:ma},{query:"Система Лира",expectedId:mb}];
  const baseline=q=>q==="Сервис Альфа"?[{id:ma}]:[{id:mb}];
  const worse=q=>q==="Сервис Альфа"?[{id:ma}]:[{id:mc}];
  const metric=compareMemoryAlgorithms(cases,baseline,worse,{persist:true});
  assert.equal(metric.accepted,false);
  assert.equal(compareMemoryAlgorithms(cases,worse,baseline).accepted,true);
  assert.equal(withCoreDatabase(db=>db.prepare("PRAGMA integrity_check").get().integrity_check),"ok");
  console.log("[YATSUMIRA CORE v8] source fusion, graph motifs, temporal changes, experience, jobs, metrics and offline quality: OK");
}finally{process.chdir(base);rmSync(dir,{recursive:true,force:true});}
