import assert from "node:assert/strict";
import {mkdtempSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {addKnowledge,coreStatus,withCoreDatabase} from "../server/core-db.mjs";
import {assertGraphRelation,recordMemoryEvent} from "../server/universal-memory-graph.mjs";
import {createMemoryTask,updateMemoryTask} from "../server/memory-v5-records.mjs";
import {proposeGraphType,reviewGraphType,proposeIdentity,mergeIdentity,splitIdentity,resolveIdentity,identityCandidates} from "../server/memory-v10-identity.mjs";
import {graphProvenance,inspectGraphRules,linkEventNode,eventHistory,proposeEventCause,inspectEventCauses,connectTaskEvent,experienceGraph} from "../server/memory-v10-events.mjs";
import {discoverGraphLinks,graphAnomalyReview,graphDiscoveryStats,knowledgeBridges} from "../server/memory-v10-discovery.mjs";
import {scheduleMemoryJob,runMemoryJob,recoverInterruptedJobs} from "../server/memory-v8-operations.mjs";
const cwd=process.cwd(),folder=mkdtempSync(join(tmpdir(),"yatsumira-v10-"));
try{
  process.chdir(folder);
  assert.equal(coreStatus().version,13);
  const a=addKnowledge({content:"«Сервис Север» использует «Модуль Луч».",sector:0,source:"note"});
  const b=addKnowledge({content:"«Сервис Северный» связан с «Модуль Луч».",sector:1,source:"note"});
  const c=addKnowledge({content:"«Модуль Луч» используется в «Лаборатория Маяк».",sector:2,source:"note"});
  const memory=id=>withCoreDatabase(db=>db.prepare("SELECT id FROM memory_entries WHERE source_kind='knowledge' AND source_id=?").get(id).id);
  const ma=memory(a.id),mb=memory(b.id),mc=memory(c.id);
  const one=assertGraphRelation({memoryId:ma,subject:"Сервис Север",subjectType:"project",predicate:"uses",object:"Модуль Луч",objectType:"module",confidence:.7});
  const two=assertGraphRelation({memoryId:mb,subject:"Сервис Северный",subjectType:"project",predicate:"uses",object:"Модуль Луч",objectType:"module"});
  const three=assertGraphRelation({memoryId:mc,subject:"Модуль Луч",subjectType:"module",predicate:"located_in",object:"Лаборатория Маяк",objectType:"organization"});
  const originalNodes=withCoreDatabase(db=>db.prepare("SELECT COUNT(*) AS n FROM graph_nodes").get().n);
  assert.equal(graphProvenance(one.id).sourceId,a.id);
  assert.equal(graphProvenance(one.id).verified,false);
  assert.equal(inspectGraphRules().ok,true);
  const type=proposeGraphType({name:"facility",memoryId:ma});
  assert.equal(type.state,"candidate");
  assert.equal(reviewGraphType(type.id,{approved:true,evidence:"Документ подтверждает тип"}).state,"reviewed");
  assert.equal(withCoreDatabase(db=>db.prepare("SELECT state FROM memory_ontology_types WHERE type_name='facility'").get().state),"reviewed");
  assert.ok(Array.isArray(identityCandidates()));
  const alias=proposeIdentity({canonicalId:one.subjectId,aliasId:two.subjectId,memoryId:mb,evidence:"Согласовано вручную"});
  assert.equal(alias.state,"proposed");
  assert.equal(resolveIdentity(two.subjectId).merged,false);
  assert.equal(mergeIdentity(alias.id,{evidence:"Проверено по первоисточнику"}).originalNodesPreserved,true);
  assert.equal(resolveIdentity(two.subjectId).canonicalId,one.subjectId);
  assert.equal(splitIdentity(alias.id,{evidence:"Ошибка сопоставления"}).state,"split");
  assert.equal(resolveIdentity(two.subjectId).canonicalId,two.subjectId);
  assert.equal(withCoreDatabase(db=>db.prepare("SELECT COUNT(*) AS n FROM graph_nodes").get().n),originalNodes);
  const links=discoverGraphLinks({limit:10,persist:true});
  assert.ok(links.candidates.some(x=>[x.leftId,x.rightId].includes(one.subjectId)&&[x.leftId,x.rightId].includes(three.objectId)));
  assert.equal(discoverGraphLinks({limit:10,persist:true}).candidates.length,links.candidates.length);
  assert.ok(graphDiscoveryStats().proposed>=1);
  const bridges=knowledgeBridges();
  assert.ok(bridges.some(x=>x.nodeId===three.subjectId));
  const anomaly=graphAnomalyReview({persist:true});
  assert.equal(anomaly.fixApplied,false);
  recordMemoryEvent({memoryId:ma,title:"Запуск проекта",eventType:"launch",occurredAt:"2026-01-01"});
  recordMemoryEvent({memoryId:mb,title:"Проверка проекта",eventType:"check",occurredAt:"2026-02-01"});
  const events=eventHistory({from:"2026-01-01",to:"2026-12-31"});
  assert.equal(events.length,2);
  const launch=events.find(x=>x.title==="Запуск проекта"),check=events.find(x=>x.title==="Проверка проекта");
  assert.equal(linkEventNode({eventId:launch.id,nodeId:one.subjectId,role:"subject"}).stored,true);
  const cause=proposeEventCause({causeEventId:launch.id,effectEventId:check.id,memoryId:mb});
  assert.equal(cause.verified,false);
  assert.equal(inspectEventCauses().length,1);
  assert.equal(inspectEventCauses({reviewedOnly:true}).length,0);
  assert.throws(()=>proposeEventCause({causeEventId:check.id,effectEventId:launch.id,memoryId:mb}),/temporal order/);
  const task=createMemoryTask({memoryId:ma,title:"Проверить проект"});
  updateMemoryTask(task.id,{status:"done",outcome:"Проверка завершена"});
  assert.equal(connectTaskEvent({taskId:task.id,eventId:check.id}).stored,true);
  assert.equal(experienceGraph().length,1);
  assert.equal(scheduleMemoryJob("v10-link-discovery",{date:"2026-11-16"}).stored,true);
  assert.equal(scheduleMemoryJob("v10-anomaly-review",{date:"2026-11-16"}).stored,true);
  assert.equal(runMemoryJob().state,"completed");
  assert.equal(runMemoryJob().state,"completed");
  assert.equal(withCoreDatabase(db=>db.prepare("PRAGMA integrity_check").get().integrity_check),"ok");
  assert.deepEqual(withCoreDatabase(db=>db.prepare("PRAGMA foreign_key_check").all()),[]);
  console.log("[YATSUMIRA CORE v10] reversible identity, provenance, types, time, causes, experience, discovery: OK");
}finally{process.chdir(cwd);rmSync(folder,{recursive:true,force:true});}
