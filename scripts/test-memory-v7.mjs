import assert from "node:assert/strict";
import {mkdtempSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {addKnowledge,coreStatus,withCoreDatabase} from "../server/core-db.mjs";
import {indexUniversalGraph,assertGraphRelation} from "../server/universal-memory-graph.mjs";
import {createMemoryTask,updateMemoryTask} from "../server/memory-v5-records.mjs";
import {reasoningStep,reasoningLink,reasoningTrace,alignmentCandidates,proposeAlignment,reviewAlignment,procedureFromTask,consolidateSources,reinforceLink,experienceTimeline,consolidateCompletedTasks} from "../server/memory-v7-experience.mjs";
import {temporalGraph,hierarchicalClusters,temporalContradictions,rankGraphPaths,graphRepairPlan} from "../server/memory-v7-graph.mjs";
const previous=process.cwd(),root=mkdtempSync(join(tmpdir(),"yatsumira-core-v7-"));
try{
  process.chdir(root);
  assert.equal(coreStatus().version,8);
  const a=addKnowledge({content:"«Платформа Звезда» использует «Движок Лира».",sector:0,source:"note"});
  const b=addKnowledge({content:"«Движок Лира» находится в «Лаборатория Север».",sector:1,source:"note"});
  const c=addKnowledge({content:"«Машина Сокол» использует «Платформа Звезда».",sector:2,source:"note"});
  const mid=id=>withCoreDatabase(db=>db.prepare("SELECT id FROM memory_entries WHERE source_kind='knowledge' AND source_id=?").get(id).id);
  const ma=mid(a.id),mb=mid(b.id),mc=mid(c.id);
  assert.equal(indexUniversalGraph({batch:30}).claims,3);
  const one=reasoningStep({sessionId:"investigation-1",stepKey:"question",kind:"question",content:"Как машина связана с лабораторией?"});
  const two=reasoningStep({sessionId:"investigation-1",stepKey:"evidence",kind:"evidence",content:"Движок Лира находится в лаборатории",evidenceIds:[mb]});
  assert.equal(reasoningStep({sessionId:"investigation-1",stepKey:"evidence",kind:"evidence",content:"Движок Лира находится в лаборатории",evidenceIds:[mb]}).stored,false);
  const three=reasoningStep({sessionId:"investigation-1",stepKey:"hypothesis",kind:"hypothesis",content:"Возможно машина связана с лабораторией",evidenceIds:[mc,ma]});
  assert.equal(reasoningLink(one.id,two.id).stored,true);
  assert.equal(reasoningLink(two.id,three.id,"supports").stored,true);
  assert.throws(()=>reasoningLink(three.id,one.id),/cycle/);
  const trace=reasoningTrace("investigation-1");
  assert.equal(trace.steps.length,3);
  assert.equal(trace.edges.length,2);
  assert.equal(trace.evidence.length,3);
  assert.equal(trace.verified,false);
  const nodes=withCoreDatabase(db=>db.prepare("SELECT id,label FROM graph_nodes").all());
  const platform=nodes.find(x=>x.label==="Платформа Звезда"),engine=nodes.find(x=>x.label==="Движок Лира");
  assert.ok(platform&&engine);
  assert.ok(Array.isArray(alignmentCandidates()));
  const alignment=proposeAlignment({leftId:platform.id,rightId:engine.id,memoryId:ma});
  assert.equal(alignment.status,"candidate");
  assert.throws(()=>reviewAlignment(alignment.id,{approved:true}),/Invalid/);
  assert.equal(reviewAlignment(alignment.id,{approved:false,evidence:"Разные сущности"}).status,"rejected");
  assert.equal(withCoreDatabase(db=>db.prepare("SELECT COUNT(*) AS n FROM graph_nodes").get().n),nodes.length);
  const task=createMemoryTask({memoryId:mc,title:"Проверить систему",checkpoint:"Шаг 1: диагностика"});
  assert.throws(()=>procedureFromTask(task.id),/Completed/);
  updateMemoryTask(task.id,{status:"done",outcome:"Диагностика завершена"});
  const procedure=procedureFromTask(task.id);
  assert.equal(procedure.stored,true);
  assert.equal(procedureFromTask(task.id).stored,false);
  const secondTask=createMemoryTask({memoryId:mb,title:"Проверить вторую систему",checkpoint:"Диагностика"});
  updateMemoryTask(secondTask.id,{status:"done",outcome:"Работа завершена"});
  assert.ok(experienceTimeline().some(row=>row.id===secondTask.id&&row.kind==="task"));
  assert.equal(consolidateCompletedTasks({limit:10}).stored,1);
  assert.equal(consolidateCompletedTasks({limit:10}).stored,0);

  const summary=consolidateSources([ma,mb,mc],{kind:"compressed"});
  assert.equal(summary.originalsPreserved,true);
  assert.equal(summary.sourceCount,3);
  const refs=withCoreDatabase(db=>db.prepare("SELECT COUNT(*) AS n FROM memory_consolidation_sources WHERE consolidation_id=?").get(summary.id).n);
  assert.equal(refs,3);
  assert.equal(withCoreDatabase(db=>db.prepare("SELECT COUNT(*) AS n FROM memory_entries WHERE state='active'").get().n),3);
  const links=withCoreDatabase(db=>db.prepare("SELECT id,score FROM memory_links LIMIT 1").get());
  if(links){const review=reinforceLink(links.id,{memoryId:ma});assert.equal(review.audited,true);assert.ok(review.score>=links.score);}
  const groups=hierarchicalClusters();
  assert.ok(groups.communities.length>0);
  assert.equal(groups.notLouvain,true);
  const paths=rankGraphPaths("Машина Сокол","Лаборатория Север",{maxHops:4});
  assert.ok(paths.length>0&&paths[0].steps.length===3);
  assert.ok(paths[0].steps.every(x=>x.memoryId));
  const historic=temporalGraph({asOf:"2025-01-01"});
  assert.equal(historic.edges.length,0);
  const current=temporalGraph();
  assert.equal(current.edges.length,3);
  assert.ok(Array.isArray(temporalContradictions()));
  assert.equal(graphRepairPlan().healthy,true);
  assert.equal(withCoreDatabase(db=>db.prepare("PRAGMA integrity_check").get().integrity_check),"ok");
  console.log("[YATSUMIRA CORE v7] thought graph, typed evidence, graph alignment, temporal paths, clustering, procedures, compression, link review: OK");
}finally{process.chdir(previous);rmSync(root,{recursive:true,force:true});}
